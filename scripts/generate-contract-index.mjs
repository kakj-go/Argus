import { writeFile } from "node:fs/promises";

const [output, ...domains] = process.argv.slice(2);
if (!output || domains.length === 0) {
  throw new Error("usage: generate-contract-index.mjs <output> <domain...>");
}

const aliases = domains.map((domain) => {
  const name = domain[0].toUpperCase() + domain.slice(1);
  return `export type { components as ${name}Components, paths as ${name}Paths } from "./${domain}.js";`;
});

const namedTypes = [
  ["common", "ApiError", "ApiError"],
  ["common", "CursorPage", "CursorPage"],
  ["common", "BatchResult", "BatchResult"],
  ["common", "ResourceRef", "ResourceRefContract"],
  ["identity", "Enterprise", "Enterprise"],
  ["identity", "PlatformUser", "PlatformUser"],
  ["identity", "EnterpriseUser", "EnterpriseUser"],
  ["identity", "Department", "Department"],
  ["identity", "Session", "Session"],
  ["identity", "ServiceAccount", "ServiceAccount"],
  ["identity", "ApiKey", "ApiKey"],
  ["authorization", "Permission", "Permission"],
  ["authorization", "Role", "Role"],
  ["authorization", "RoleBinding", "RoleBinding"],
  ["authorization", "DataScope", "DataScope"],
  ["authorization", "AuthorizationDecision", "AuthorizationDecision"],
  ["labels", "Labels", "Labels"],
  ["labels", "LabelSelector", "LabelSelector"],
  ["action", "PendingActionPublic", "PendingActionPublic"],
  ["action", "Execution", "Execution"],
  ["action", "ActionBinding", "ActionBinding"],
  ["card", "CardManifest", "CardManifest"],
  ["card", "RenderPlan", "RenderPlan"],
  ["card", "BridgeMessage", "BridgeMessage"],
  ["agent", "ConversationEvent", "ConversationEvent"],
  ["agent", "AgentEvent", "AgentEvent"],
  ["agent", "Run", "Run"],
  ["agent", "Step", "Step"],
  ["agent", "Task", "Task"],
  ["agent", "RunCheckpoint", "RunCheckpoint"],
  ["agent", "ContextSnapshot", "ContextSnapshot"],
  ["agent", "ContextBudget", "ContextBudget"],
  ["agent", "ModelCall", "ModelCall"],
  ["agent", "ToolResultProjection", "ToolResultProjection"],
  ["stream", "StreamEventEnvelope", "StreamEventEnvelope"],
];

const namedAliases = namedTypes
  .filter(([domain]) => domains.includes(domain))
  .map(
    ([domain, schema, alias]) =>
      `export type ${alias} = import("./${domain}.js").components["schemas"]["${schema}"];`,
  );

const content = [
  "/** Code generated by scripts/generate-contract-index.mjs. DO NOT EDIT. */",
  ...aliases,
  "",
  ...namedAliases,
  "",
].join("\n");

await writeFile(output, content, "utf8");
