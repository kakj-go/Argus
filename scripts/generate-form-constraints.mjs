import { readFile, writeFile } from "node:fs/promises";

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  throw new Error(
    "usage: node scripts/generate-form-constraints.mjs INPUT OUTPUT",
  );
}

const document = JSON.parse(await readFile(input, "utf8"));
const schemas = document.components?.schemas ?? {};

function resolve(schema, seen = new Set()) {
  if (!schema || typeof schema !== "object") return {};
  if (schema.$ref?.startsWith("#/components/schemas/")) {
    const name = schema.$ref.slice("#/components/schemas/".length);
    if (seen.has(name)) return {};
    return resolve(schemas[name], new Set([...seen, name]));
  }
  if (Array.isArray(schema.allOf)) {
    return Object.assign(
      {},
      ...schema.allOf.map((item) => resolve(item, seen)),
    );
  }
  return schema;
}

function schemaConstraint(property, required) {
  const resolved = resolve(property);
  const constraint = { required };
  for (const key of [
    "type",
    "format",
    "minLength",
    "maxLength",
    "minimum",
    "maximum",
    "exclusiveMinimum",
    "exclusiveMaximum",
    "minItems",
    "maxItems",
    "uniqueItems",
    "pattern",
  ]) {
    if (resolved[key] !== undefined) constraint[key] = resolved[key];
  }
  if (Array.isArray(resolved.enum)) constraint.enum = resolved.enum;
  return constraint;
}

const constraints = {};
const valueConstraints = {};
for (const schemaName of Object.keys(schemas).sort()) {
  const schema = resolve(schemas[schemaName], new Set([schemaName]));
  if (!schema.properties || typeof schema.properties !== "object") {
    const constraint = schemaConstraint(schema, true);
    if (Object.keys(constraint).length > 1) {
      valueConstraints[schemaName] = constraint;
    }
    continue;
  }
  const required = new Set(schema.required ?? []);
  constraints[schemaName] = Object.fromEntries(
    Object.keys(schema.properties)
      .sort()
      .map((field) => [
        field,
        schemaConstraint(schema.properties[field], required.has(field)),
      ]),
  );
}

const serializedConstraints = `{
${Object.entries(constraints)
  .map(
    ([schema, fields]) =>
      `  ${JSON.stringify(schema)}: ${JSON.stringify(fields)},`,
  )
  .join("\n")}
}`;

const serializedValueConstraints = `{
${Object.entries(valueConstraints)
  .map(
    ([schema, constraint]) =>
      `  ${JSON.stringify(schema)}: ${JSON.stringify(constraint)},`,
  )
  .join("\n")}
}`;

const source = `/** Code generated by scripts/generate-form-constraints.mjs. DO NOT EDIT. */
export interface FormConstraint {
  readonly required: boolean;
  readonly type?: string | readonly string[];
  readonly format?: string;
  readonly minLength?: number;
  readonly maxLength?: number;
  readonly minimum?: number;
  readonly maximum?: number;
  readonly exclusiveMinimum?: number | boolean;
  readonly exclusiveMaximum?: number | boolean;
  readonly minItems?: number;
  readonly maxItems?: number;
  readonly uniqueItems?: boolean;
  readonly pattern?: string;
  readonly enum?: readonly unknown[];
}

export const FORM_CONSTRAINTS: Readonly<Record<string, Readonly<Record<string, FormConstraint>>>> = ${serializedConstraints};
export const FORM_VALUE_CONSTRAINTS: Readonly<Record<string, FormConstraint>> = ${serializedValueConstraints};

export function formConstraint(schema: string, field: string): FormConstraint {
  const constraint = FORM_CONSTRAINTS[schema]?.[field];
  if (!constraint) throw new Error(\`Missing OpenAPI form constraint: \${schema}.\${field}\`);
  return constraint;
}

export function formValueConstraint(schema: string): FormConstraint {
  const constraint = FORM_VALUE_CONSTRAINTS[schema];
  if (!constraint) throw new Error(\`Missing OpenAPI form value constraint: \${schema}\`);
  return constraint;
}
`;

await writeFile(output, source);
