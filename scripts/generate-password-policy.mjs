import { readFile, writeFile } from "node:fs/promises";

const [inputPath, goOutputPath, tsOutputPath] = process.argv.slice(2);
if (!inputPath || !goOutputPath || !tsOutputPath) {
  throw new Error(
    "usage: node scripts/generate-password-policy.mjs INPUT GO_OUTPUT TS_OUTPUT",
  );
}

const policy = JSON.parse(await readFile(inputPath, "utf8"));
if (
  policy.version !== "argus.password_policy/v1" ||
  !Number.isInteger(policy.min_length) ||
  !Number.isInteger(policy.max_length) ||
  policy.min_length < 1 ||
  policy.max_length < policy.min_length ||
  !Array.isArray(policy.rules) ||
  !Array.isArray(policy.common_passwords)
) {
  throw new Error("invalid Argus password policy contract");
}
const rules = [...new Set(policy.rules)];
const commonPasswords = [...new Set(policy.common_passwords)];
if (
  rules.length !== policy.rules.length ||
  commonPasswords.length !== policy.common_passwords.length ||
  rules.some((rule) => !/^[a-z][a-z0-9_]*$/.test(rule)) ||
  commonPasswords.some((password) => typeof password !== "string")
) {
  throw new Error("password policy rules and common passwords must be unique");
}

const goName = (value) =>
  value
    .split("_")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
const quoteGo = (value) => JSON.stringify(value);
const goRules = rules
  .map((rule) => `\tRule${goName(rule)} = ${quoteGo(rule)}`)
  .join("\n");
const goPasswords = commonPasswords
  .map((password) => `\t${quoteGo(password)},`)
  .join("\n");
const goSource = `// Code generated by scripts/generate-password-policy.mjs; DO NOT EDIT.

package passwordpolicy

const (
\tVersion = ${quoteGo(policy.version)}
\tMinLength = ${policy.min_length}
\tMaxLength = ${policy.max_length}
${goRules}
)

var CommonPasswords = []string{
${goPasswords}
}
`;

const tsSource = `// Code generated by scripts/generate-password-policy.mjs; DO NOT EDIT.

export const PASSWORD_POLICY_CONTRACT = ${JSON.stringify(
  {
    version: policy.version,
    minLength: policy.min_length,
    maxLength: policy.max_length,
    rules,
    commonPasswords,
  },
  null,
  2,
)} as const;

export type GeneratedPasswordPolicyRule =
  (typeof PASSWORD_POLICY_CONTRACT.rules)[number];
`;

await writeFile(goOutputPath, goSource);
await writeFile(tsOutputPath, tsSource);
