import { readFile, unlink, writeFile } from "node:fs/promises";

const [input] = process.argv.slice(2);
if (!input) {
  throw new Error("usage: split-generated-go-server.mjs <server.gen.go>");
}

const source = await readFile(input, "utf8");
for (const suffix of ["chi_extra.gen.go", "chi_extra2.gen.go", "responses.gen.go", "responses_extra.gen.go", "strict.gen.go", "chi.gen.go"]) {
  const stalePath = input.replace(/server\.gen\.go$/, suffix);
  try {
    await unlink(stalePath);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}
const marker = "// StrictServerInterface represents all server handlers.";
const offset = source.indexOf(marker);
if (offset < 0) {
  throw new Error(`strict server marker not found in ${input}`);
}

const packageMatch = source.match(/^package ([A-Za-z0-9_]+)$/m);
if (!packageMatch) {
  throw new Error(`package declaration not found in ${input}`);
}

let chiSource = `${source
  .slice(0, offset)
  .replace(/^\s*"context"\n/m, "")
  .trimEnd()}\n`;
const strictBody = source.slice(offset);
const strictImports = ["context"];
if (strictBody.includes("json.")) strictImports.push("encoding/json");
if (strictBody.includes("fmt.")) strictImports.push("fmt");
if (strictBody.includes("openapi_types.")) {
  strictImports.push('openapi_types "github.com/oapi-codegen/runtime/types"');
}
if (strictBody.includes("http.")) strictImports.push("net/http");
const strictSource = `// Package ${packageMatch[1]} provides primitives to interact with the openapi HTTP API.
//
// Code generated by scripts/split-generated-go-server.mjs. DO NOT EDIT.
package ${packageMatch[1]}

import (
${strictImports.map((value) => value.includes(' ') ? `\t${value}` : `\t"${value}"`).join("\n")}
)

${strictBody.trimEnd()}
`;

const generatedHeader = (imports, body) => `// Package ${packageMatch[1]} provides primitives to interact with the openapi HTTP API.
//
// Code generated by scripts/split-generated-go-server.mjs. DO NOT EDIT.
package ${packageMatch[1]}

import (
${imports.map((value) => value.includes(" ") ? `\t${value}` : `\t"${value}"`).join("\n")}
)

${body.trimEnd()}
`;

const serverImports = (body) => {
  const imports = [];
  if (body.includes("bytes.")) imports.push("bytes");
  if (body.includes("json.")) imports.push("encoding/json");
  if (body.includes("fmt.")) imports.push("fmt");
  if (body.includes("http.")) imports.push("net/http");
  if (body.includes("openapi_types.")) imports.push('openapi_types "github.com/oapi-codegen/runtime/types"');
  return imports;
};

const chiPath = input.replace(/server\.gen\.go$/, "chi.gen.go");
const strictPath = input.replace(/server\.gen\.go$/, "strict.gen.go");
const responseMarker = /type List[A-Za-z0-9]+RequestObject struct \{/;
const responseMatch = chiSource.match(responseMarker);
const responseOffset = responseMatch ? responseMatch.index : -1;
if (responseOffset >= 0 && chiSource.split("\n").length > 2000) {
  // 拆分点之前可能仍遗留使用 bytes/json 的响应对象(如首个 List 操作之前
  // 的 Get* 操作),因此 import 块必须按剩余内容重建,不能无条件剥离。
  const responseBody = chiSource.slice(responseOffset);
  const importEnd = chiSource.indexOf(")\n\n");
  if (importEnd < 0) throw new Error(`imports not found in ${input}`);
  const keptBody = chiSource.slice(importEnd + 3, responseOffset).trimEnd();
  const keptImports = [];
  if (keptBody.includes("bytes.")) keptImports.push("bytes");
  if (keptBody.includes("json.")) keptImports.push("encoding/json");
  keptImports.push("errors", "fmt", "net/http");
  keptImports.push("github.com/go-chi/chi/v5", "github.com/oapi-codegen/runtime");
  if (keptBody.includes("openapi_types.")) keptImports.push('openapi_types "github.com/oapi-codegen/runtime/types"');
  chiSource = generatedHeader(keptImports, keptBody);
  const responsePath = input.replace(/server\.gen\.go$/, "responses.gen.go");
  const responseMarkers = [...responseBody.matchAll(/^type [A-Za-z0-9]+RequestObject struct \{/gm)];
  if (responseBody.split("\n").length > 1900 && responseMarkers.length > 1) {
    const responseSplit = responseMarkers.find((match) => match.index > responseBody.length / 2)?.index;
    if (responseSplit == null) {
      throw new Error(`unable to split generated response objects ${input}`);
    }
    const first = responseBody.slice(0, responseSplit);
    const second = responseBody.slice(responseSplit);
    await writeFile(responsePath, generatedHeader(serverImports(first), first), "utf8");
    await writeFile(input.replace(/server\.gen\.go$/, "responses_extra.gen.go"), generatedHeader(serverImports(second), second), "utf8");
  } else {
    await writeFile(responsePath, generatedHeader(serverImports(responseBody), responseBody), "utf8");
  }
}

// Keep generated files below the repository's 2,000-line contract gate. The
// generated middleware is declaration-order independent within one package, so
// it can be split at an operation boundary without changing the API surface.
if (chiSource.split("\n").length > 2000) {
  const middlewareMarkers = [...chiSource.matchAll(/^\/\/ .* operation middleware$/gm)];
  const split = middlewareMarkers.find((match) => chiSource.slice(0, match.index).split("\n").length >= 1700)?.index;
  if (split == null) {
    throw new Error(`unable to split generated chi server ${input}`);
  }
  const extraPath = input.replace(/server\.gen\.go$/, "chi_extra.gen.go");
  const extraBody = chiSource.slice(split);
  chiSource = chiSource.slice(0, split).trimEnd() + "\n";
  const chiImports = ["errors", "fmt", "net/http", "github.com/go-chi/chi/v5", "github.com/oapi-codegen/runtime", 'openapi_types "github.com/oapi-codegen/runtime/types"'];
  const extraMarkers = [...extraBody.matchAll(/^\/\/ .* operation middleware$/gm)];
  if (extraBody.split("\n").length > 2000 && extraMarkers.length > 1) {
    const extraSplit = extraMarkers.find((match) => match.index > extraBody.length / 2)?.index;
    if (extraSplit == null) {
      throw new Error(`unable to split generated chi middleware ${input}`);
    }
    const extra2Path = extraPath.replace(/\.gen\.go$/, "2.gen.go");
    await writeFile(extraPath, generatedHeader(chiImports, extraBody.slice(0, extraSplit)), "utf8");
    await writeFile(extra2Path, generatedHeader(chiImports, extraBody.slice(extraSplit)), "utf8");
  } else {
    await writeFile(extraPath, generatedHeader(chiImports, extraBody), "utf8");
  }
}
await writeFile(chiPath, chiSource, "utf8");
await writeFile(strictPath, strictSource, "utf8");
await unlink(input);
