import { readFile, unlink, writeFile } from "node:fs/promises";

const [input] = process.argv.slice(2);
if (!input) {
  throw new Error("usage: split-generated-go-server.mjs <server.gen.go>");
}

const source = await readFile(input, "utf8");
const marker = "// StrictServerInterface represents all server handlers.";
const offset = source.indexOf(marker);
if (offset < 0) {
  throw new Error(`strict server marker not found in ${input}`);
}

const packageMatch = source.match(/^package ([A-Za-z0-9_]+)$/m);
if (!packageMatch) {
  throw new Error(`package declaration not found in ${input}`);
}

let chiSource = `${source
  .slice(0, offset)
  .replace(/^\s*"context"\n/m, "")
  .trimEnd()}\n`;
const strictBody = source.slice(offset);
const strictImports = ["context"];
if (strictBody.includes("json.")) strictImports.push("encoding/json");
if (strictBody.includes("fmt.")) strictImports.push("fmt");
if (strictBody.includes("openapi_types.")) {
  strictImports.push('openapi_types "github.com/oapi-codegen/runtime/types"');
}
if (strictBody.includes("http.")) strictImports.push("net/http");
const strictSource = `// Package ${packageMatch[1]} provides primitives to interact with the openapi HTTP API.
//
// Code generated by scripts/split-generated-go-server.mjs. DO NOT EDIT.
package ${packageMatch[1]}

import (
${strictImports.map((value) => value.includes(' ') ? `\t${value}` : `\t"${value}"`).join("\n")}
)

${strictBody.trimEnd()}
`;

const chiPath = input.replace(/server\.gen\.go$/, "chi.gen.go");
const strictPath = input.replace(/server\.gen\.go$/, "strict.gen.go");
const responseMarker = "type ListRemoteAccessGrantsRequestObject struct {";
const responseOffset = chiSource.indexOf(responseMarker);
if (responseOffset >= 0 && chiSource.split("\n").length > 2000) {
  const responseBody = chiSource.slice(responseOffset);
  chiSource = `${chiSource
    .slice(0, responseOffset)
    .replace(/^\s*"bytes"\n/m, "")
    .replace(/^\s*"encoding\/json"\n/m, "")
    .trimEnd()}\n`;
  const responsePath = input.replace(/server\.gen\.go$/, "responses.gen.go");
  const responseSource = `// Package ${packageMatch[1]} provides primitives to interact with the openapi HTTP API.
//
// Code generated by scripts/split-generated-go-server.mjs. DO NOT EDIT.
package ${packageMatch[1]}

import (
\t"bytes"
\t"encoding/json"
\t"net/http"

\topenapi_types "github.com/oapi-codegen/runtime/types"
)

${responseBody.trimEnd()}
`;
  await writeFile(responsePath, responseSource, "utf8");
}
await writeFile(chiPath, chiSource, "utf8");
await writeFile(strictPath, strictSource, "utf8");
await unlink(input);
