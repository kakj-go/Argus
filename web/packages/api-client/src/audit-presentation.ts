export type AuditPresentationKind =
  | "actions"
  | "resourceTypes"
  | "actorTypes";

export function auditCodeKey(code: string): string {
  return code.replaceAll(".", "_").replaceAll("-", "_");
}

export function auditPresentationKey(
  namespace: string,
  kind: AuditPresentationKind,
  code: string,
): string {
  return `${namespace}.${kind}.${auditCodeKey(code)}`;
}

export function humanizeAuditCode(code: string): string {
  return code
    .split(/[._-]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}
